/** Даты по традиции: основной срок — первая среда декабря, дополнительные — первая среда февраля и вторая среда апреля. */
function nthWednesday(year, month, n) {
  const d = new Date(Date.UTC(year, month, 1, 3));
  while (d.getUTCDay() !== 3) d.setUTCDate(d.getUTCDate() + 1);
  d.setUTCDate(d.getUTCDate() + 7 * (n - 1));
  return d;
}
export function itogDates(now = new Date()) {
  const y = now.getMonth() >= 6 ? now.getFullYear() : now.getFullYear() - 1; // учебный год начинается летом
  return [
    { when: nthWednesday(y, 11, 1), label: "основной срок" },
    { when: nthWednesday(y + 1, 1, 1), label: "дополнительный срок" },
    { when: nthWednesday(y + 1, 3, 2), label: "дополнительный срок" },
  ];
}

