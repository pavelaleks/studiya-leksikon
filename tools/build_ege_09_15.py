INSTR_LETTER = (
    "Укажите варианты ответов, в которых во всех словах одного ряда пропущена одна и та же буква. "
    "Запишите номера ответов."
)


def item(task: int, i: int, lines: list[str], answer: str, explanation: str, rule_ids: list[str], instruction: str = INSTR_LETTER):
    return {
        "id": f"ege-{task:02d}-{i:02d}",
        "type": "ege-short",
        "egeTask": task,
        "section": "ege",
        "title": f"Задание {task} · вариант {i}",
        "instruction": instruction,
        "lines": [f"{n}) {row}" for n, row in enumerate(lines, 1)],
        "answer": answer,
        "answerMode": "digits-any",
        "explanation": explanation,
        "ruleIds": rule_ids,
    }


def pack(rows):
    """rows: (text, letter_or_None). letter set => same missing letter."""
    lines = [r[0] for r in rows]
    letters = [r[1] for r in rows]
    ans = "".join(str(i) for i, let in enumerate(letters, 1) if let)
    bits = []
    for i, let in enumerate(letters, 1):
        if let:
            bits.append(f"{i} — везде «{let}»")
        else:
            bits.append(f"{i} — разные буквы")
    return lines, ans, "; ".join(bits) + "."


def rotate(seq, n):
    n %= len(seq)
    return seq[n:] + seq[:n]


def build_from_pools(task, same, mixed, rules, extra_instr=None):
    items = []
    for i in range(1, 41):
        # 2–4 «чистых» ряда, остальные смешанные
        n_same = 2 + (i % 3)  # 2, 3, 4
        s = rotate(same, i * 3)[:n_same]
        m = rotate(mixed, i * 2)[: 5 - n_same]
        rows = s + m
        rows = rotate(rows, i % 5)
        lines, ans, expl = pack(rows)
        items.append(item(task, i, lines, ans, expl, rules, extra_instr or INSTR_LETTER))
    return items


