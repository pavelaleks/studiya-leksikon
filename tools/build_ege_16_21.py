def short(task, i, instruction, lines=None, stimulus=None, text=None, answer="", explanation="", rules=None, mode="digits-any"):
    item = {
        "id": f"ege-{task:02d}-{i:02d}",
        "type": "ege-short",
        "egeTask": task,
        "section": "ege",
        "title": f"Задание {task} · вариант {i}",
        "instruction": instruction,
        "answer": answer,
        "answerMode": mode,
        "explanation": explanation,
        "ruleIds": rules or [],
    }
    if lines is not None:
        item["lines"] = lines
    if stimulus:
        item["stimulus"] = stimulus
    if text:
        item["text"] = text
    return item


