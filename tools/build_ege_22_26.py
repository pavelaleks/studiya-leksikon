def split_sents(text: str) -> list[str]:
    raw = text.replace("\n", " ").strip()
    parts, buf = [], ""
    for ch in raw:
        buf += ch
        if ch in ".!?…" and len(buf.strip()) > 1:
            parts.append(buf.strip())
            buf = ""
    if buf.strip():
        parts.append(buf.strip())
    return parts


def numbered(text: str) -> str:
    sents = split_sents(text)
    return " ".join(f"({i}) {s}" for i, s in enumerate(sents, 1))


def item(task, i, **kw):
    d = {
        "id": f"ege-{task:02d}-{i:02d}",
        "type": kw.get("type", "ege-short"),
        "egeTask": task,
        "section": "ege",
        "title": f"Задание {task} · вариант {i}",
        "instruction": kw["instruction"],
        "answer": kw["answer"],
        "answerMode": kw.get("answerMode", "digits-any"),
        "explanation": kw["explanation"],
        "ruleIds": kw.get("ruleIds", []),
    }
    for k in ("lines", "stimulus", "text", "left", "right", "answers"):
        if k in kw and kw[k] is not None:
            d[k] = kw[k]
    return d


