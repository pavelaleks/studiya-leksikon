def apply_marks(text: str) -> str:
    if not text or "{" in text:
        return text
    out = text
    for src, dst in sorted(WORDS.items(), key=lambda kv: -len(kv[0])):
        out = out.replace(src, dst)
    return out


def enrich_file(path: Path) -> None:
    data = json.loads(path.read_text(encoding="utf-8"))
    for chapter in data.get("chapters", []):
        for rule in chapter.get("rules", []):
            spec = SPECIAL.get(rule["id"])
            if spec:
                rule["summary"] = spec.get("summary", rule.get("summary"))
                if spec.get("theory"):
                    rule["theory"] = spec["theory"]
                if spec.get("exceptions"):
                    rule["exceptions"] = spec["exceptions"]
                continue
            if rule.get("summary"):
                rule["summary"] = apply_marks(rule["summary"])
            for block in rule.get("theory") or []:
                if not block.get("body") and rule.get("summary"):
                    block["body"] = rule["summary"]
                for key in ("heading", "body", "note"):
                    if block.get(key):
                        block[key] = apply_marks(block[key])
                if block.get("examples"):
                    block["examples"] = [apply_marks(x) for x in block["examples"]]
            if rule.get("exceptions"):
                rule["exceptions"] = [apply_marks(x) for x in rule["exceptions"]]
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("updated", path.name)


def main():
    enrich_file(ROOT / "orthography.json")
    enrich_file(ROOT / "punctuation.json")


if __name__ == "__main__":
    main()
