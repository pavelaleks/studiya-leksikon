GRADES = [8, 9, 10, 11]


def R(n, slug, title, summary, theory, mistakes=None, exceptions=None):
    item = {
        "id": f"stil-{n}",
        "slug": slug,
        "title": title,
        "grades": GRADES,
        "rosenthal": {"paragraph": n},
        "summary": summary,
        "theory": theory,
    }
    if exceptions:
        item["exceptions"] = exceptions
    if mistakes:
        item["typicalMistakes"] = mistakes
    return item


def T(heading, body, examples=None, table=None, note=None):
    block = {"heading": heading, "body": body}
    if table:
        block["table"] = table
    if examples:
        block["examples"] = examples
    if note:
        block["note"] = note
    return block


