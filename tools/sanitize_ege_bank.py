def clean_line(s: str) -> str:
    t = HINT.sub("", s)
    for a, b in NN_FIX:
        t = t.replace(a, b)
    return re.sub(r" {2,}", " ", t).strip()


def main() -> None:
    nfix = 0
    for path in sorted(ROOT.glob("task-*.json")):
        if path.stem == "task-22":
            continue
        items = json.loads(path.read_text(encoding="utf-8"))
        for it in items:
            old = json.dumps(it, ensure_ascii=False)
            if it.get("egeTask") == 5 and it.get("instruction") == INSTR5_OLD:
                it["instruction"] = INSTR5_NEW
            if "lines" in it:
                it["lines"] = [clean_line(x) for x in it["lines"]]
            if "stimulus" in it:
                it["stimulus"] = clean_line(it["stimulus"])
            extra = PATCH.get(it["id"])
            if extra:
                it.update(extra)
                if "answers" in extra and extra["answers"] is None:
                    it.pop("answers", None)
            if json.dumps(it, ensure_ascii=False) != old:
                nfix += 1
        path.write_text(json.dumps(items, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"поправлено карточек: {nfix}")


if __name__ == "__main__":
    main()
