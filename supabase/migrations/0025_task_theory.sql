## Частые ловушки

- **Метафора или олицетворение?** Если неживое получает именно человеческое действие или чувство (*лес шепчет*, *ветер плачет*), это олицетворение. Если перенос по сходству без «оживления» (*золото листвы*), это метафора.
- **Метафора или сравнение?** Есть «как, словно, будто» или творительный падеж — сравнение. Нет — метафора.
- **Анафора или эпифора?** Анафора — повтор в **начале**, эпифора — в **конце**.
- **Аллитерация или ассонанс?** Согласные — аллитерация, гласные — ассонанс.
- **Метонимия или синекдоха?** Синекдоха — всегда про количество: часть вместо целого или одно вместо многих. Остальные переносы по связи — метонимия.
- **Антитеза или контекстные антонимы?** Антонимы — это слова, антитеза — построение всего фрагмента на противопоставлении. Если в списке есть оба, смотрите, что именно выделено в примере.
- **Градация или ряд однородных?** Градация — только когда есть нарастание или ослабление смысла.
- **Риторическое обращение или обычное?** Риторическое обращено к тому, кто не может ответить: природе, предмету, эпохе. Слово, зависящее от глагола (*спорить с веком*), — дополнение, а не обращение.
- **Парцелляция или неполное предложение?** Парцелляция — оторванная точкой часть, которая грамматически продолжает предыдущее предложение.
- **Инверсия** чаще всего — прилагательное после существительного или сказуемое перед подлежащим. В стихах её много, отвечайте «инверсия», только если других явных средств нет.
