create or replace function public.track_ok(p_source text)
returns boolean language sql stable security definer set search_path = '' as $$
  select public.is_teacher()
      or coalesce((select case when cardinality(p.courses) = 0 then true
                               else exists (select 1 from unnest(p.courses) c where
                                 case p_source when 'ege-lit' then c like 'lit:%'
                                               when 'ege-rus' then c in ('rus:10', 'rus:11')
                                               when 'oge-rus' then c = 'rus:9'
                                               when 'vpr-rus' then c in ('rus:5', 'rus:6', 'rus:7', 'rus:8')
                                               else false end)
                          end
                   from public.profiles p where p.id = auth.uid()), false);
$$;
grant execute on function public.track_ok(text) to authenticated;

create table if not exists public.task_theory (
  source text not null check (source in ('ege-rus', 'oge-rus', 'vpr-rus', 'ege-lit')),
  task_no int not null check (task_no between 1 and 40),
  body text not null,
  updated_at timestamptz not null default now(),
  primary key (source, task_no)
);
alter table public.task_theory enable row level security;

drop policy if exists task_theory_read on public.task_theory;
create policy task_theory_read on public.task_theory for select to authenticated
  using (public.has_access() and public.track_ok(source));
drop policy if exists task_theory_write on public.task_theory;
create policy task_theory_write on public.task_theory for all to authenticated
  using (public.is_teacher()) with check (public.is_teacher());

