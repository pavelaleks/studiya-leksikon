## Как устроено задание

- Даны 5 фрагментов (А–Д) и список из 9 терминов. Каждому фрагменту нужно подобрать средство выразительности.
- Ответ: 5 цифр подряд в порядке А, Б, В, Г, Д, без пробелов и запятых.
- Максимум 2 балла. Если неверны 1–2 позиции, ставят 1 балл.

**Алгоритм**

1. Сначала прочитайте все 9 терминов и отметьте «лишние», которые явно не встречаются.
2. Начинайте с фрагментов, где средство видно по форме: вопрос, восклицание, повтор в начале строк, «как/словно», точка посреди мысли.
3. Тропы (метафору, олицетворение, метонимию) определяйте в последнюю очередь — они самые спорные.
4. Проверьте, нет ли во фрагменте второго средства, которое тоже есть в списке. Выбирайте то, что выражено ярче всего и только там.
5. Сверьте порядок цифр с буквами.

